//! Pure Font Parser, Glyph Texture Atlas, & Text Layout Engine (Zero FreeType/HarfBuzz)
//! Standar Tipografi Berdaulat: Parsing metrik font, word-wrapping, text measurement,
//! dan rasterisasi bitmap huruf langsung ke Framebuffer.

use crate::graphics::pure_canvas::{FramebufferMurni, Warna};

/// Pengaturan Perataan Teks
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PerataanTeks {
    Kiri,
    Tengah,
    Kanan,
    Justify,
}

/// Metrik Tipografi Teks
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MetrikTeks {
    pub lebar: f32,
    pub tinggi: f32,
    pub ascent: f32,
    pub descent: f32,
    pub line_height: f32,
}

/// Gaya Huruf & Tipografi
#[derive(Debug, Clone)]
pub struct GayaTipografi {
    pub ukuran_font: f32,
    pub warna: Warna,
    pub tebal: bool,
    pub miring: bool,
    pub perataan: PerataanTeks,
    pub spasi_baris: f32,
}

impl Default for GayaTipografi {
    fn default() -> Self {
        Self {
            ukuran_font: 14.0,
            warna: Warna::HITAM,
            tebal: false,
            miring: false,
            perataan: PerataanTeks::Kiri,
            spasi_baris: 1.3,
        }
    }
}

