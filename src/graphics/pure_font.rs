    /// Hitung Ukuran Metrik Dimensi Teks
    pub fn hitung_metrik(teks: &str, gaya: &GayaTipografi) -> MetrikTeks {
        let skala = (gaya.ukuran_font / 8.0).max(0.5);
        let char_width = 8.0 * skala;
        let line_height = gaya.ukuran_font * gaya.spasi_baris;

        let mut max_lebar = 0.0f32;
        let mut total_baris = 0;

        for line in teks.lines() {
            total_baris += 1;
            let len = line.chars().count() as f32;
            let cur_w = len * char_width;
            if cur_w > max_lebar {
                max_lebar = cur_w;
            }
        }
        if total_baris == 0 {
            total_baris = 1;
        }

        MetrikTeks {
            lebar: max_lebar,
            tinggi: total_baris as f32 * line_height,
            ascent: gaya.ukuran_font * 0.8,
            descent: gaya.ukuran_font * 0.2,
            line_height,
        }
    }

    /// Render Teks ke Framebuffer dengan Perataan dan Skala Font
    pub fn gambar_teks(
        fb: &mut FramebufferMurni,
        teks: &str,
        x: f32,
        y: f32,
        gaya: &GayaTipografi,
    ) {
        let skala = (gaya.ukuran_font / 8.0).max(0.5);
        let char_w = 8.0 * skala;
        let line_h = gaya.ukuran_font * gaya.spasi_baris;

        let mut cur_y = y;
        for line in teks.lines() {
            let line_len = line.chars().count() as f32;
            let line_w = line_len * char_w;

            let cur_x = match gaya.perataan {
                PerataanTeks::Kiri => x,
                PerataanTeks::Tengah => x - line_w / 2.0,
                PerataanTeks::Kanan => x - line_w,
                PerataanTeks::Justify => x,
            };

            let mut char_x = cur_x;
            for c in line.chars() {
                let bitmap = Self::ambil_bitmap_glyph(c);
                for row in 0..8 {
                    let byte = bitmap[row];
                    for col in 0..8 {
                        if (byte & (0x80 >> col)) != 0 {
                            let px = char_x + (col as f32) * skala;
                            let py = cur_y + (row as f32) * skala;

                            let x_start = px.floor() as i32;
                            let y_start = py.floor() as i32;
                            let x_end = (px + skala).ceil() as i32;
                            let y_end = (py + skala).ceil() as i32;

                            for sy in y_start..y_end {
                                for sx in x_start..x_end {
                                    fb.set_piksel(sx, sy, gaya.warna);
                                }
                            }
                        }
                    }
                }
                char_x += char_w;
            }
            cur_y += line_h;
        }
    }
