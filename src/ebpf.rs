//! Linux Kernel eBPF & XDP High-Performance Engine (ebpf.rs)
//! Menyediakan emisi kode C eBPF native untuk:
//! 1. XDP (eXpress Data Path) Line-Rate Network Packet Filtering
//! 2. Kprobes / Uprobes untuk low-overhead kernel & user-space tracing
//! 3. BPF Ring-Buffer & Perf Event Stream untuk observability real-time

use crate::ast::*;
use crate::error::Galat;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EbpfProgramType {
    XdpFilter,
    Kprobe(String),
    Uprobe(String),
    Tracepoint(String),
    SocketFilter,
}

#[derive(Debug, Clone)]
pub struct XdpRule {
    pub protocol: String,
    pub port: u16,
    pub action: String, // "XDP_DROP", "XDP_PASS", "XDP_TX"
}

pub struct EbpfEmitter {
    buffer: String,
    xdp_rules: Vec<XdpRule>,
}

impl EbpfEmitter {
    pub fn new() -> Self {
        Self {
            buffer: String::new(),
            xdp_rules: Vec::new(),
        }
    }

    pub fn add_xdp_rule(&mut self, protocol: &str, port: u16, action: &str) {
        self.xdp_rules.push(XdpRule {
            protocol: protocol.to_uppercase(),
            port,
            action: action.to_uppercase(),
        });
    }

    /// Menghasilkan program C eBPF XDP Line-Rate Packet Filter
    pub fn emit_xdp_c(&mut self) -> String {
        self.buffer.clear();
        self.buffer.push_str("// === Linux Kernel eBPF XDP (eXpress Data Path) Filter ===\n");
        self.buffer.push_str("// Generated by Widya eBPF Engine for line-rate packet processing\n\n");
        self.buffer.push_str("#include <linux/bpf.h>\n");
        self.buffer.push_str("#include <linux/if_ether.h>\n");
        self.buffer.push_str("#include <linux/ip.h>\n");
        self.buffer.push_str("#include <linux/tcp.h>\n");
        self.buffer.push_str("#include <linux/udp.h>\n");
        self.buffer.push_str("#include <bpf/bpf_helpers.h>\n");
        self.buffer.push_str("#include <bpf/bpf_endian.h>\n\n");

        self.buffer.push_str("struct {\n");
        self.buffer.push_str("    __uint(type, BPF_MAP_TYPE_RINGBUF);\n");
        self.buffer.push_str("    __uint(max_entries, 256 * 1024);\n");
        self.buffer.push_str("} events_ringbuf SEC(\".maps\");\n\n");

        self.buffer.push_str("SEC(\"xdp\")\n");
        self.buffer.push_str("int widya_xdp_router(struct xdp_md *ctx) {\n");
        self.buffer.push_str("    void *data = (void *)(long)ctx->data;\n");
        self.buffer.push_str("    void *data_end = (void *)(long)ctx->data_end;\n");
        self.buffer.push_str("    struct ethhdr *eth = data;\n\n");
        self.buffer.push_str("    if ((void *)(eth + 1) > data_end) return XDP_PASS;\n");
        self.buffer.push_str("    if (eth->h_proto != bpf_htons(ETH_P_IP)) return XDP_PASS;\n\n");
        self.buffer.push_str("    struct iphdr *ip = (void *)(eth + 1);\n");
        self.buffer.push_str("    if ((void *)(ip + 1) > data_end) return XDP_PASS;\n\n");

        for rule in &self.xdp_rules {
            if rule.protocol == "TCP" {
                self.buffer.push_str("    if (ip->protocol == IPPROTO_TCP) {\n");
                self.buffer.push_str("        struct tcphdr *tcp = (void *)(ip + 1);\n");
                self.buffer.push_str("        if ((void *)(tcp + 1) <= data_end) {\n");
                self.buffer.push_str(&format!("            if (bpf_ntohs(tcp->dest) == {}) return {};\n", rule.port, rule.action));
                self.buffer.push_str("        }\n");
                self.buffer.push_str("    }\n");
            } else if rule.protocol == "UDP" {
                self.buffer.push_str("    if (ip->protocol == IPPROTO_UDP) {\n");
                self.buffer.push_str("        struct udphdr *udp = (void *)(ip + 1);\n");
                self.buffer.push_str("        if ((void *)(udp + 1) <= data_end) {\n");
                self.buffer.push_str(&format!("            if (bpf_ntohs(udp->dest) == {}) return {};\n", rule.port, rule.action));
                self.buffer.push_str("        }\n");
                self.buffer.push_str("    }\n");
            }
        }

        self.buffer.push_str("    return XDP_PASS;\n");
        self.buffer.push_str("}\n\n");
        self.buffer.push_str("char _license[] SEC(\"license\") = \"GPL\";\n");
        self.buffer.clone()
    }

    /// Menghasilkan program eBPF kprobe / uprobe untuk pelacakan fungsi
    pub fn emit_ebpf_c(&mut self, program: &Program) -> Result<String, Galat> {
        self.buffer.clear();
        self.buffer.push_str("// === Linux Kernel eBPF (Extended Berkeley Packet Filter) Program ===\n");
        self.buffer.push_str("// Generated automatically by Widya-Lang eBPF Emitter\n\n");
        self.buffer.push_str("#include <linux/bpf.h>\n");
        self.buffer.push_str("#include <bpf/bpf_helpers.h>\n\n");

        self.buffer.push_str("struct {\n");
        self.buffer.push_str("    __uint(type, BPF_MAP_TYPE_HASH);\n");
        self.buffer.push_str("    __uint(max_entries, 1024);\n");
        self.buffer.push_str("    __type(key, __u32);\n");
        self.buffer.push_str("    __type(value, __u64);\n");
        self.buffer.push_str("} packet_counter_map SEC(\".maps\");\n\n");

        for stmt in &program.statements {
            if let Stmt::FunctionDecl { name, .. } = stmt {
                self.buffer.push_str(&format!("// Widya eBPF Handler: {}\n", name));
                self.buffer.push_str(&format!("SEC(\"kprobe/{}\")\n", name));
                self.buffer.push_str(&format!("int widya_kprobe_{}(struct pt_regs *ctx) {{\n", name));
                self.buffer.push_str("    __u32 key = 0;\n");
                self.buffer.push_str("    __u64 *val = bpf_map_lookup_elem(&packet_counter_map, &key);\n");
                self.buffer.push_str("    if (val) {\n");
                self.buffer.push_str("        __sync_fetch_and_add(val, 1);\n");
                self.buffer.push_str("    }\n");
                self.buffer.push_str("    return 0;\n");
                self.buffer.push_str("}\n\n");
            }
        }

        self.buffer.push_str("char _license[] SEC(\"license\") = \"GPL\";\n");
        Ok(self.buffer.clone())
    }
}

/// Laporan Keamanan dan Verifikasi In-Memory Program eBPF
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EbpfSafetyReport {
    pub is_safe: bool,
    pub estimated_instructions: usize,
    pub max_allowed_instructions: usize,
    pub has_unbounded_loops: bool,
    pub memory_access_bounded: bool,
    pub license_valid: bool,
}

/// Verifikator Statis Bytecode/Source eBPF untuk menjamin tidak crash di kernel
pub struct EbpfVerifier;

impl EbpfVerifier {
    pub fn verify_c_code(c_source: &str) -> EbpfSafetyReport {
        let license_valid = c_source.contains("SEC(\"license\")");
        let has_unbounded_loops = c_source.contains("while(1)") || c_source.contains("for(;;)") || c_source.contains("while (1)");
        let memory_access_bounded = c_source.contains("data_end");
        let line_count = c_source.lines().count();
        let estimated_instructions = line_count * 4;
        let max_allowed_instructions = 4096;

        let is_safe = license_valid && !has_unbounded_loops && memory_access_bounded && estimated_instructions <= max_allowed_instructions;

        EbpfSafetyReport {
            is_safe,
            estimated_instructions,
            max_allowed_instructions,
            has_unbounded_loops,
            memory_access_bounded,
            license_valid,
        }
    }
}
